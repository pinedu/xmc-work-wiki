def derive_stage(text: str) -> str:
    """v1.2 增补：识别案情所处的阶段（pre/during/post）。

    优先级：post > during > pre（事故优先；仅在无事故/无正在作业时判为事前）。
    未命中任何关键词时返回 "unknown"。
    """
    blob = text or ""
    for stage in ("post", "during", "pre"):
        hits = _has_any(blob, STAGE_KEYWORDS[stage]["pos"])
        if hits:
            return stage
    return "unknown"


def derive_attributes(text: str) -> dict:
    """从原文派生安全属性：{attr: True/False}，判不出则不出现该键。附证据关键词。

    v1.2 增补：双重否定识别 —— 若正向短语出现在双重否定语境下，视为肯定（即属性为 True）。
    """
    blob = text or ""
    attrs: dict[str, bool] = {}
    evidences: dict[str, list[str]] = {}
    for attr, meta in ATTR_KEYWORD.items():
        neg, pos = meta.get("neg", []), meta.get("pos", [])
        hit_neg = _has_any(blob, neg)
        # v1.2 增补：双重否定豁免（窗口=20，覆盖"不是没戴安全帽"等口语化表达）
        # 窗口必须足够大以容纳"不是没"+"否定短语自身起始字符"
        if hit_neg and not _double_negated(blob, hit_neg, window=20):
            attrs[attr] = False
            evidences[attr] = hit_neg
            continue
        hit_pos = _has_any(blob, pos)
        if hit_pos:
            attrs[attr] = True
            evidences[attr] = hit_pos
    return {"attrs": attrs, "evidences": evidences}


def _height_m(text: str) -> float | None:
    """从文本提取作业高度（米），用于 B1 等级判定。"""
    m = re.search(r"(\d+(?:\.\d+)?)\s*(?:米|m|M)\s*高?", text or "")
    if m:
        return float(m.group(1))
    return None


