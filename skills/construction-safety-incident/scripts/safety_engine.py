# 否定标记：出现在"正向短语"前若干字符内，表示该短语被否定（如"没有混凝土保温养护"）
_NEG_MARKERS = ("没有", "未", "无", "缺少", "缺失", "不", "没", "尚未", "未进行", "没有做")

# v1.2 增补：双重否定标记（"不是没戴安全帽" = 戴了）
_DOUBLE_NEG_MARKERS = ("不是没有", "不是没", "并非未", "并非没有", "并非没", "并非无",
                       "并不是没有", "并不是没", "并不是无", "并非没有不", "不是没有不")


def _has_any(blob: str, kws: list[str]) -> list[str]:
    """返回命中的关键词列表（空列表 = 未命中）。"""
    return [k for k in kws if k and k in blob]


def _negated(blob: str, phrases: list[str], window: int = 5) -> bool:
    """正向短语是否处于否定语境（其前 window 字符内有否定标记）。"""
    for ph in phrases:
        idx = blob.find(ph)
        while idx >= 0:
            pre = blob[max(0, idx - window):idx]
            if any(m in pre for m in _NEG_MARKERS):
                return True
            idx = blob.find(ph, idx + 1)
    return False


def _double_negated(blob: str, phrases: list[str], window: int = 8) -> bool:
    """v1.2 增补：检测双重否定（"不是没戴" → 表示已戴）。

    逻辑：当否定短语（如"没戴安全帽"）的前后 window 字符内出现"不是"+"没/未/无"
    双重否定组合时，原始否定被反转，应判定为肯定。

    关键：短语自身的首字符也算入窗口（"没戴安全帽"的"没"必须被纳入判断），
    否则"不是没戴安全帽"这种口语化表达无法被识别。
    """
    # 双重否定组合：前导否定词 + 后随否定词（"没/未/无"）
    patterns = ["不是没", "并非没", "不是没有", "并非没有",
                "不是未", "并非未", "不是无", "并非无",
                "并不是没", "并不是未", "并不是无", "并不是没有"]
    for ph in phrases:
        idx = blob.find(ph)
        while idx >= 0:
            # 窗口：从短语前 window 字符开始，包含短语首字符
            pre = blob[max(0, idx - window):idx + 1]   # +1 包含短语首字符
            if any(pat in pre for pat in patterns):
                return True
            idx = blob.find(ph, idx + 1)
    return False


