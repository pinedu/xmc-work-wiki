def _b1_level(text: str) -> str:
    h = _height_m(text)
    if h is None:
        return "较大风险（高度未知，若 >5m 应升为重大）"
    return "重大风险" if h > 5 else "较大风险"


def run(text: str) -> dict:
    """执行确定性识别：返回 {attributes, findings, strategies, stage, compound_findings}。

    v1.2 升级：
    - 新增 stage 字段（pre/during/post/unknown）
    - 新增 compound_findings 字段（复合规则叠加判定）
    """
    d = derive_attributes(text)
    attrs, ev = d["attrs"], d["evidences"]
    stage = derive_stage(text)

    def ok(kind: str, attr: str) -> bool:
        want = (kind == "attr_true")
        return attrs.get(attr) is want

    findings = []
    for r in RULES:
        if all(ok(k, a) for k, a in r["conditions"]):
            level = _b1_level(text) if r["id"] in ("B1", "B6") else r["level"]
            evidence = []
            for k, a in r["conditions"]:
                hits = ev.get(a, [])
                tag = "命中" if k == "attr_true" else "否定命中"
                evidence.append(f"{ATTR_KEYWORD[a]['cn']}（{tag}：{'、'.join(hits) or '—'}）")
            findings.append({
                "rule_id": r["id"], "rule_name": r["name"], "risk_type": r["risk_type"],
                "level": level, "responsible": r["responsible"], "evidence": evidence,
                "downgradable": r["downgradable"], "downgrade_explain": r["downgrade_explain"],
            })
    hit_ids = {f["rule_id"] for f in findings}
    strategies = [s for s in STRATEGIES if s["rule_ref"] in hit_ids]

    # v1.2 增补：复合规则判定（场景叠加）
    compound_findings = []
    for cr in COMPOUND_RULES:
        # 必须有任一 trigger_rule 命中（说明基础风险已存在）
        if any(rid in hit_ids for rid in cr["trigger_rules"]) and all(ok(k, a) for k, a in cr["attr_conditions"]):
            compound_findings.append({
                "compound_id": cr["id"],
                "compound_name": cr["name"],
                "risk_level_upgrade": cr["risk_level_upgrade"],
                "responsible": cr["responsible"],
                "explain": cr["explain"],
                "trigger_rules": cr["trigger_rules"],
            })

    return {
        "attributes": attrs,
        "findings": findings,
        "strategies": strategies,
        "stage": stage,
        "compound_findings": compound_findings,
    }


def _stage_label(stage: str) -> str:
    """v1.2：阶段字段对外标签。"""
    return {
        "pre": "事前·隐患阶段（尚未发生事故，仅违规）",
        "during": "事中·违规进行中（仍在作业、未停止）",
        "post": "事后·已发生事故",
        "unknown": "未识别（建议人工补判）",
    }.get(stage, "未识别")


def render_markdown(text: str, result: dict) -> str:
    out = ["# 建筑安全事件风险识别（确定性引擎）", ""]
    fs, ss = result["findings"], result["strategies"]
    compounds = result.get("compound_findings", [])
    stage = result.get("stage", "unknown")
    if not fs:
        out += ["> 未命中任何安全风险规则（B1–B21）。",
                "> 提示：请确认是否为安全类案情；非安全类（质量/工期/合同/欠薪）请改用对应技能。", ""]
        return "\n".join(out)
    out += [f"**案件阶段**：{_stage_label(stage)}", ""]
    out += [f"## 风险发现（{len(fs)} 项）", ""]
    for f in fs:
        dg = "可降级" if f["downgradable"] else "不可降级（法定刚性/既定事实）"
        out += [f"### [{f['rule_id']}] {f['rule_name']}",
                f"- 风险类型：{f['risk_type']}",
                f"- 等级：{f['level']}",
                f"- 责任主体：{'、'.join(f['responsible'])}",
                f"- 处理空间：{dg} —— {f['downgrade_explain']}",
                f"- 判定依据：{'；'.join(f['evidence'])}", ""]
    # v1.2 增补：复合规则输出
    if compounds:
        out += [f"## 场景叠加判定（{len(compounds)} 项·升级警告）", ""]
        for c in compounds:
            out += [f"### [{c['compound_id']}] {c['compound_name']}",
                    f"- 风险等级升级：{c['risk_level_upgrade']}",
                    f"- 责任主体：{'、'.join(c['responsible'])}",
                    f"- 联动基础规则：{', '.join(c['trigger_rules'])}",
                    f"- 叠加解释：{c['explain']}", ""]
    out += [f"## 处置策略（{len(ss)} 项，建设单位立场）", ""]
    for s in ss:
        out += [f"### [{s['id']}] {s['name']}", f"- 可行性：{s['feasibility']}"]
        for i, w in enumerate(s["windows"], 1):
            out += [f"{i}. {w['action']}（输出：{w['output']}）"]
        out += [f"- 作用：{s['effect']}", ""]
    out += ["## 处置红线", ""] + [f"- {p}" for p in DESIGN_PRINCIPLES] + [""]
    out += [f"**法律依据**：{LEGAL_BASIS}", ""]
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="建筑安全事件处置 · 确定性风险识别引擎")
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--text", help="直接传入案情文本")
    src.add_argument("--file", help="从文件读取案情文本（UTF-8）")
    ap.add_argument("--format", choices=["json", "md"], default="md", help="输出格式（默认 md）")
    args = ap.parse_args(argv)

    text = args.text if args.text is not None else open(args.file, encoding="utf-8").read()
    result = run(text)
    if args.format == "json":
        print(json.dumps({"input": text, **result}, ensure_ascii=False, indent=2))
    else:
        print(render_markdown(text, result))
    return 0


if __name__ == "__main__":
    sys.exit(main())
